export const GLYPH_W = 5
export const GLYPH_H = 7
/** One blank column between glyphs, so words read as words at any scale. */
export const GLYPH_GAP = 1

export type Pixel = { x: number; y: number }

/** The lit cells of a string, in glyph-grid coordinates. */
export function pixelsFor(text: string): { pixels: Pixel[]; width: number } {
  const chars = [...text.toUpperCase()]
  const pixels: Pixel[] = []

  chars.forEach((char, index) => {
    const rows = (GLYPHS[char] ?? GLYPHS['?']).split('|')
    const originX = index * (GLYPH_W + GLYPH_GAP)
    rows.forEach((row, y) => {
      ;[...row].forEach((cell, x) => {
        if (cell === '#') pixels.push({ x: originX + x, y })
      })
    })
  })

  const width = chars.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP
  return { pixels, width: Math.max(width, 0) }
}

/** How many grid columns a headline of this many characters occupies. */
export function widthOf(text: string): number {
  return Math.max(text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP, 0)
}
